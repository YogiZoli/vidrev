"""Builds the app.vidrev.app/ landing from the approved landing (index.html).

Same 13 sections as vidrev.app (Drive "06 vidrev Landing szekciók"); only the
calls to action change for the app host (DECISIONS A-18): Get started goes to
/signup, Log in to /login, the free audit to its own page.

Run after every change to index.html:
    python design/landing/build-app-landing.py
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "design" / "landing" / "index.html"
OUT = ROOT / "src" / "app" / "landing-html.ts"
AUDIT = "/where-i-lose-money-on-youtube"

REPLACEMENTS = [
    # Navigation
    ('<a href="https://app.vidrev.app/login">Sign in</a>', '<a href="/login">Log in</a>'),
    (
        '<a class="vidrev-btn" style="padding:10px 16px;font-size:15px" href="#vidrev-audit">See where I lose money</a>',
        '<a class="vidrev-btn" style="padding:10px 16px;font-size:15px" href="/signup">Get started</a>',
    ),
    # Hero: Get started first, the audit second
    (
        '<form class="vidrev-hero-form" action="https://app.vidrev.app/audit" method="get">\n'
        '        <input name="channel" placeholder="@yourchannel" aria-label="Your YouTube channel">\n'
        '        <button class="vidrev-btn" type="submit">See where I lose money on YouTube</button>\n'
        "      </form>",
        '<div style="display:flex;gap:12px;flex-wrap:wrap;margin-top:24px">\n'
        '        <a class="vidrev-btn" href="/signup">Get started</a>\n'
        f'        <a class="vidrev-btn vidrev-btn-ghost" href="{AUDIT}">See where I lose money on YouTube</a>\n'
        "      </div>",
    ),
    (
        "Free, 30 seconds, no sign-in. Only public data is read.",
        "Start free for 14 days with Google or email. No card. The money check is free and needs no sign-in.",
    ),
    # Audit section and links
    ('action="https://app.vidrev.app/audit"', f'action="{AUDIT}"'),
    ('href="https://app.vidrev.app/audit/sample"', f'href="{AUDIT}/sample"'),
    ('href="#vidrev-checkout"', 'href="/signup"'),
    # Final CTA
    (
        '<a class="vidrev-btn" href="#vidrev-audit">See where I lose money on YouTube</a>\n'
        '      <a class="vidrev-btn vidrev-btn-ghost" style="color:#fff;border-color:rgba(255,255,255,.3)" href="#vidrev-pricing">Founding 100</a>',
        '<a class="vidrev-btn" href="/signup">Get started</a>\n'
        f'      <a class="vidrev-btn vidrev-btn-ghost" style="color:#fff;border-color:rgba(255,255,255,.3)" href="{AUDIT}">See where I lose money</a>',
    ),
    ('<a href="#vidrev-audit">See where I lose money</a>', f'<a href="{AUDIT}">See where I lose money</a>'),
    # Same host
    ('href="https://vidrev.app/"', 'href="/"'),
    ('src="https://app.vidrev.app/vidrev-logo.png"', 'src="/vidrev-logo.png"'),
    ('href="https://app.vidrev.app/', 'href="/'),
]


def main() -> None:
    html = SRC.read_text(encoding="utf-8")
    for old, new in REPLACEMENTS:
        if old not in html:
            raise SystemExit(f"not found in index.html, update build-app-landing.py: {old[:80]!r}")
        html = html.replace(old, new)  # every occurrence
    OUT.write_text(
        "// Generated by design/landing/build-app-landing.py from design/landing/index.html. Do not edit.\n"
        f"export const LANDING_HTML = {json.dumps(html, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
